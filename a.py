import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

sns.set_theme(style="whitegrid")

# Load data
try:
    df = pd.read_csv('/content/airbnbdata.csv')
except FileNotFoundError:
    raise FileNotFoundError("Please make sure '/content/airbnbdata.csv' exists before running this cell.")

# Prepare data
data = df.copy()

data["price"] = pd.to_numeric(
    data["price"].astype(str)
    .str.replace("$", "", regex=False)
    .str.replace(",", "", regex=False),
    errors="coerce"
)

data = data[data["price"] > 0].copy()

# 1. Median price by room type
room_prices = (
    data.groupby("room_type")["price"]
    .median()
    .sort_values(ascending=False)
)

# 2. Hotel room price by neighbourhood
hotel = data[
    data["room_type"].str.strip().str.lower() == "hotel room"
]

hotel_prices = (
    hotel.groupby("neighbourhood")["price"]
    .median()
    .sort_values(ascending=False)
)

# 3. Listing count by neighbourhood
listing_counts = (
    df.groupby("neighbourhood")
    .size()
    .sort_values(ascending=False)
)

top10 = listing_counts.head(10).sort_values()

# Dashboard layout
fig = plt.figure(figsize=(18, 13))
fig.suptitle(
    "AIRBNB LISTING ANALYSIS DASHBOARD",
    fontsize=22, fontweight="bold", y=0.98
)

# KPI cards
kpis = [
    ("TOTAL LISTINGS", f"{len(df):,}"),
    ("ROOM TYPES", str(df["room_type"].nunique())),
    ("NEIGHBOURHOODS", str(df["neighbourhood"].nunique())),
    ("HOTEL LISTINGS", f"{len(hotel):,}")
]

for i, (label, value) in enumerate(kpis):
    ax = fig.add_axes([0.06 + i * 0.23, 0.83, 0.20, 0.09])
    ax.set_facecolor("#EAF2F8")
    ax.text(0.5, 0.68, label, ha="center",
            fontsize=10, fontweight="bold")
    ax.text(0.5, 0.28, value, ha="center",
            fontsize=20, fontweight="bold")
    ax.set_xticks([])
    ax.set_yticks([])
    for spine in ax.spines.values():
        spine.set_visible(False)

# Chart 1: Room type prices
ax1 = fig.add_axes([0.07, 0.52, 0.40, 0.25])
room_prices.plot(kind="bar", ax=ax1)
ax1.set_title("Median Price Across Room Types",
              fontweight="bold")
ax1.set_xlabel("Room Type")
ax1.set_ylabel("Median Price")
ax1.tick_params(axis="x", rotation=25)

# Chart 2: Hotel room prices
ax2 = fig.add_axes([0.55, 0.52, 0.38, 0.25])
hotel_prices.plot(kind="bar", ax=ax2)
ax2.set_title("Hotel Room Price Across Neighbourhoods",
              fontweight="bold")
ax2.set_xlabel("Neighbourhood")
ax2.set_ylabel("Median Price")
ax2.tick_params(axis="x", rotation=35)

# Chart 3: Top 10 neighbourhoods
ax3 = fig.add_axes([0.18, 0.10, 0.65, 0.32])
top10.plot(kind="barh", ax=ax3)
ax3.set_title("Top 10 Neighbourhoods by Listing Count",
              fontweight="bold")
ax3.set_xlabel("Number of Listings")
ax3.set_ylabel("Neighbourhood")

plt.show()

