import plotly.express as px

# Ensure we have a numeric price column and remove rows with missing (NaN) or zero prices
plot_data = df.copy()
plot_data['price'] = pd.to_numeric(
    plot_data['price'].astype(str).str.replace('$', '', regex=False)
                     .str.replace(',', '', regex=False),
    errors='coerce'
)
plot_data = plot_data.dropna(subset=['price', 'latitude', 'longitude'])
plot_data = plot_data[plot_data['price'] > 0]

# Plot the map using the cleaned data
fig = px.scatter_map(plot_data, lat='latitude',
                     lon='longitude',
                     size='price',
                     size_max=15,
                     color='room_type',
                     hover_name='name',
                     hover_data=['price', 'room_type'],
                     zoom=10,
                     height=500)
fig.show()

