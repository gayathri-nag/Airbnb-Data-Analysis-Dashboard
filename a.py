import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv('/content/airbnbdata.csv')

sns.set_theme(style='whitegrid')

print(df.shape)
print(df.columns.tolist())

# Clean price column
df['price'] = pd.to_numeric(
    df['price'].astype(str).str.replace('$', '', regex=False)
                    .str.replace(',', '', regex=False),
    errors='coerce'
)

room_price = (
    df[df['price'] > 0]
    .groupby('room_type')['price']
    .median()
    .sort_values(ascending=False)
)

print(room_price)

room_price.plot(kind='bar', figsize=(8, 5))
plt.title('Median Price Across Room Types')
plt.xlabel('Room Type')
plt.ylabel('Median Price')
plt.xticks(rotation=30, ha='right')
plt.tight_layout()
plt.show()

hotel = df[
    (df['room_type'].str.strip().str.lower() == 'hotel room') &
    (df['price'] > 0)
]

hotel_price = (
    hotel.groupby('neighbourhood')['price']
    .median()
    .sort_values(ascending=False)
)

print(hotel_price)

hotel_price.plot(kind='bar', figsize=(10, 5))
